def render(kpts, out_png):
    # 画到更高分辨率再缩小，抗锯齿
    S = 2
    img = Image.new('L', (W*S, H*S), 0)
    d = ImageDraw.Draw(img)
    pts = [(x*W*S, y*H*S) for x, y in kpts]
    for (i, j, r, g) in BONES:
        d.line([pts[i], pts[j]], fill=g, width=int(r*S*1.5))
        # 端点圆（让关节处圆润）
        for k in (i, j):
            x, y = pts[k]
            d.ellipse([x-r*S, y-r*S, x+r*S, y+r*S], fill=g)
    img = img.resize((W, H), Image.LANCZOS)
    img.save(out_png)

